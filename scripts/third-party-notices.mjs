import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Reviewed browser runtime closure, plus Workbox code emitted by generateSW.
// Do not include build/test tools or type-only packages in deployed notices.
const packages = [
  '@babel/helpers',
  '@supabase/auth-js',
  '@supabase/functions-js',
  '@supabase/phoenix',
  '@supabase/postgrest-js',
  '@supabase/realtime-js',
  '@supabase/storage-js',
  '@supabase/supabase-js',
  '@trickfilm400/rollup-plugin-off-main-thread',
  '@zxing/browser',
  '@zxing/library',
  'iceberg-js',
  'idb',
  'lucide-react',
  'react',
  'react-dom',
  'scheduler',
  'ts-custom-error',
  'tslib',
  'workbox-cacheable-response',
  'workbox-core',
  'workbox-expiration',
  'workbox-precaching',
  'workbox-routing',
  'workbox-strategies',
];
const root = fileURLToPath(new URL('../', import.meta.url));
const lock = JSON.parse(readFileSync(resolve(root, 'package-lock.json'), 'utf8'));
const normalize = (value) => value.replaceAll('\r\n', '\n').trim();
const sections = packages.map((name) => {
  const folder = resolve(root, 'node_modules', name);
  const metadata = JSON.parse(readFileSync(resolve(folder, 'package.json'), 'utf8'));
  const locked = lock.packages[`node_modules/${name}`];
  if (!locked || locked.version !== metadata.version)
    throw new Error(`Run npm ci: installed/locked version mismatch for ${name}`);
  const files = readdirSync(folder)
    .filter((file) => /^(licen[cs]e|notice|copyrightnotice)(\.|$)/i.test(file))
    .sort();
  if (!files.some((file) => /^licen[cs]e(\.|$)/i.test(file)))
    throw new Error(`Review missing license for ${name}`);
  return [
    `${name}@${metadata.version} (${metadata.license})`,
    ...(name === '@trickfilm400/rollup-plugin-off-main-thread'
      ? [
          'The emitted AMD loader is generated/minified from loader.ejs; its source notice follows.',
          normalize(
            readFileSync(resolve(folder, 'loader.ejs'), 'utf8').match(/^\/\*\*[\s\S]*?\*\//)[0],
          ),
        ]
      : []),
    ...files.map((file) => `${file}\n\n${normalize(readFileSync(resolve(folder, file), 'utf8'))}`),
  ].join('\n\n');
});
const output =
  [
    'Sacré bleu — third-party software notices',
    'Generated by npm run notices:generate from locked, installed package license files.',
    'These components retain their own licenses. See THIRD_PARTY_NOTICES.md in the source repository for scope and Open Food Facts/artwork information.',
    'Project code and documentation license:\n\n' +
      normalize(readFileSync(resolve(root, 'LICENSE'), 'utf8')),
    'Mascot artwork by Eloane ROURE (original and derivatives), MIT:\n\n' +
      normalize(readFileSync(resolve(root, 'assets/branding/LICENSE'), 'utf8')),
    ...sections,
  ].join('\n\n' + '='.repeat(72) + '\n\n') + '\n';
const target = resolve(root, 'public/THIRD_PARTY_NOTICES.txt');
if (process.argv.slice(2).some((arg) => arg !== '--check')) throw new Error('Unknown argument');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== output)
    throw new Error('Notices changed; run npm run notices:generate and review the result');
  console.log(`Redistribution notices match ${packages.length} locked runtime packages.`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote redistribution notices for ${packages.length} runtime packages.`);
}
